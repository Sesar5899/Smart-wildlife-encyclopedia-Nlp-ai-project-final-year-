"""The one place this site talks to a generative model.

Answers are generated by DeepSeek's OpenAI-compatible chat completions API.  The
module stays small on purpose: it holds the credential, the wire format and
the stream parser, so ``app.py`` and ``admin.py`` never assemble a provider
request of their own and cannot drift apart.

The key is server-side only.  It is never rendered into a template, never
sent to browser JavaScript, and never echoed back inside an error message.
"""

from __future__ import annotations

import json

import requests

from config import Config


class LLMError(RuntimeError):
    """A request to the generator could not be completed."""


NOT_CONFIGURED = (
    "AI ဝန်ဆောင်မှုကို မပြင်ဆင်ရသေးပါ။ .env ဖိုင်တွင် DEEPSEEK_API_KEY ကို ထည့်ပါ။"
)


def configured():
    """Whether an API key is present at all."""
    return bool(Config.DEEPSEEK_API_KEY)


def _headers():
    return {
        "Authorization": f"Bearer {Config.DEEPSEEK_API_KEY}",
        "Content-Type": "application/json",
    }


def available_models():
    """Every model this key may call, or an empty list when unreachable."""
    if not configured():
        return []
    try:
        response = requests.get(
            f"{Config.DEEPSEEK_BASE_URL}/models",
            headers=_headers(),
            timeout=(
                Config.DEEPSEEK_CONNECT_TIMEOUT,
                min(Config.DEEPSEEK_READ_TIMEOUT, 30),
            ),
        )
        response.raise_for_status()
        return sorted(
            item["id"]
            for item in response.json().get("data", [])
            if isinstance(item, dict) and item.get("id")
        )
    except (requests.RequestException, ValueError, TypeError, KeyError):
        return []


def status():
    """What the chat's connection panel shows, in one dictionary."""
    if not configured():
        return {
            "status": "unconfigured",
            "models": [],
            "configured_model": Config.DEEPSEEK_MODEL,
            "configured_model_available": False,
        }
    models = available_models()
    return {
        "status": "online" if models else "offline",
        "models": models,
        "configured_model": Config.DEEPSEEK_MODEL,
        "configured_model_available": Config.DEEPSEEK_MODEL in models,
    }


def _error_detail(response):
    """The provider's own message for a refused request, without the key."""
    try:
        payload = response.json()
    except ValueError:
        return (response.text or "")[:400]
    error = payload.get("error")
    if isinstance(error, dict):
        return str(error.get("message") or error)[:400]
    return str(error or payload)[:400]


def open_stream(messages, model=None, read_timeout=None):
    """Start one streamed completion and return the open response.

    Everything that can be known before the first token — no key, a refused
    request, an unreachable host — is raised here as :class:`LLMError`, so a
    caller can answer 503 instead of opening a stream that carries only an
    error.  The caller owns the response and must close it.
    """
    if not configured():
        raise LLMError(NOT_CONFIGURED)

    payload = {
        "model": model or Config.DEEPSEEK_MODEL,
        "messages": messages,
        "stream": True,
        # The encyclopedia needs the final answer, not the model's private
        # reasoning stream. Disabling thinking also improves first-token time.
        "thinking": {"type": "disabled"},
        "temperature": Config.DEEPSEEK_TEMPERATURE,
        "max_tokens": Config.DEEPSEEK_MAX_TOKENS,
    }
    try:
        response = requests.post(
            f"{Config.DEEPSEEK_BASE_URL}/chat/completions",
            headers=_headers(),
            json=payload,
            stream=True,
            timeout=(
                Config.DEEPSEEK_CONNECT_TIMEOUT,
                read_timeout or Config.DEEPSEEK_READ_TIMEOUT,
            ),
        )
    except requests.RequestException as error:
        raise LLMError(f"AI ဝန်ဆောင်မှုကို ချိတ်ဆက်မရပါ — {error}") from error

    if response.status_code != 200:
        detail = _error_detail(response)
        response.close()
        raise LLMError(f"DeepSeek: {detail}")
    return response


def iter_deltas(response):
    """Yield the reply text of an open stream, one delta at a time.

    DeepSeek speaks server-sent events: each interesting line is ``data:`` plus a
    JSON chunk, and the stream ends with ``data: [DONE]``.  Anything that is
    neither is ignored rather than treated as content, so keep-alive comments
    and future fields cannot end up inside a member's answer.
    """
    # An event stream carries no charset, and requests then falls back to
    # ISO-8859-1 — which turns every Burmese answer into mojibake.  Say utf-8
    # before a single line is read.
    response.encoding = "utf-8"
    try:
        for raw_line in response.iter_lines(decode_unicode=True):
            if not raw_line:
                continue
            line = raw_line.strip()
            if not line.startswith("data:"):
                continue
            data = line[len("data:"):].strip()
            if data == "[DONE]":
                return
            try:
                chunk = json.loads(data)
            except json.JSONDecodeError:
                continue
            if chunk.get("error"):
                error = chunk["error"]
                message = (
                    error.get("message") if isinstance(error, dict) else error
                )
                raise LLMError(f"DeepSeek: {message}")
            for choice in chunk.get("choices") or []:
                content = (choice.get("delta") or {}).get("content")
                if content:
                    yield content
    except requests.RequestException as error:
        raise LLMError(f"AI ချိတ်ဆက်မှု ပြတ်တောက်သွားသည် — {error}") from error
