import os

from dotenv import load_dotenv

# Read the local .env whichever way the app is started.  ``flask run`` loads it
# on its own, ``python app.py`` does not, and a generator key that only works
# under one of the two is a trap.
load_dotenv(os.path.join(os.path.abspath(os.path.dirname(__file__)), ".env"))

BASE_DIR = os.path.abspath(os.path.dirname(__file__))


class Config:
    SECRET_KEY = os.environ.get("SECRET_KEY", "myanmar-wildlife-encyclopedia-2026")
    DATABASE = os.environ.get("DATABASE", os.path.join(BASE_DIR, "wildlife.db"))
    APP_HOST = os.environ.get("APP_HOST", "127.0.0.1")
    APP_PORT = int(os.environ.get("APP_PORT", "2000"))
    # Answers are generated by DeepSeek's OpenAI-compatible chat completions API.
    # The key is server-side only: it is never rendered into a page and never
    # reaches browser JavaScript.
    DEEPSEEK_API_KEY = os.environ.get("DEEPSEEK_API_KEY", "").strip()
    DEEPSEEK_BASE_URL = os.environ.get(
        "DEEPSEEK_BASE_URL", "https://api.deepseek.com"
    ).rstrip("/")
    DEEPSEEK_MODEL = os.environ.get("DEEPSEEK_MODEL", "deepseek-flash")
    # Low temperature keeps both grounded and general-knowledge replies stable.
    DEEPSEEK_TEMPERATURE = float(os.environ.get("DEEPSEEK_TEMPERATURE", "0.2"))
    DEEPSEEK_MAX_TOKENS = int(os.environ.get("DEEPSEEK_MAX_TOKENS", "1600"))
    DEEPSEEK_CONNECT_TIMEOUT = float(
        os.environ.get("DEEPSEEK_CONNECT_TIMEOUT", "10")
    )
    DEEPSEEK_READ_TIMEOUT = float(os.environ.get("DEEPSEEK_READ_TIMEOUT", "180"))
    # Embeddings are created only by administrator actions and stored locally.
    # Member chat never sends text to OpenAI; it reads this SQLite index and
    # falls back to lexical retrieval if its exact question was not pre-cached.
    OPENAI_API_KEY = os.environ.get("OPENAI_API_KEY", "").strip()
    OPENAI_BASE_URL = os.environ.get("OPENAI_BASE_URL", "https://api.openai.com/v1")
    OPENAI_EMBED_MODEL = os.environ.get(
        "OPENAI_EMBED_MODEL", "text-embedding-3-small"
    )
    OPENAI_EMBED_DIMENSIONS = int(os.environ.get("OPENAI_EMBED_DIMENSIONS", "1536"))
    EMBED_THRESHOLD = float(os.environ.get("EMBED_THRESHOLD", "0.55"))
    EMBED_ENABLED = os.environ.get("EMBED_ENABLED", "1").lower() not in ("0", "false", "no")
    # Used only by an administrator publishing or explicitly indexing content.
    OPENAI_EMBED_TIMEOUT = float(os.environ.get("OPENAI_EMBED_TIMEOUT", "60"))
    OPENAI_EMBED_BATCH_SIZE = max(
        1, min(int(os.environ.get("OPENAI_EMBED_BATCH_SIZE", "64")), 256)
    )
    # Public text is required before DeepSeek answers a question the local
    # record cannot. Without a readable source, the chat reports no answer.
    EXTERNAL_SOURCES_ENABLED = os.environ.get(
        "EXTERNAL_SOURCES_ENABLED", "1"
    ).lower() not in ("0", "false", "no")
    # A member is waiting on this call, so it is short and tried once.
    EXTERNAL_TIMEOUT = float(os.environ.get("EXTERNAL_TIMEOUT", "12"))
    # An article changes far more slowly than a chat asks for it.
    EXTERNAL_CACHE_TTL = float(os.environ.get("EXTERNAL_CACHE_TTL", "86400"))
    # Comma-separated accounts that are allowed to use the publishing console.
    # Keeping this explicit avoids making the first registrant an administrator.
    ADMIN_EMAILS = {
        email.strip().lower()
        for email in os.environ.get("ADMIN_EMAILS", "").split(",")
        if email.strip()
    }
    MAX_CONTENT_LENGTH = int(os.environ.get("MAX_UPLOAD_BYTES", 12 * 1024 * 1024))
